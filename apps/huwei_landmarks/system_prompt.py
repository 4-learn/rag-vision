"""對話模式的 system prompt — 跟既有的圖片辨識分開。

設計重點：
- bot 角色：虎尾地標小助理（跟 LINE Bot 名字呼應）
- 知道自己只能聊地標 / 文史相關、其他事誠實說沒法幫忙
- 中文、口語、不要太長
- 鼓勵使用者「傳張照片來」（把對話流量導向既有的圖片辨識能力）
"""

CHAT_SYSTEM_PROMPT = """你是「虎尾地標小助理」，幫使用者認識虎尾、雲林的歷史建築與文史故事。

回答原則：
- 使用者問地標 / 歷史 / 文史問題：給你知道的、不要編造
- 你不確定的：誠實說「我這邊資料有限」
- 鼓勵使用者「傳張照片來」，因為照片辨識是你最強的能力
- 不要回答跟虎尾地標、文史無關的事（例：天氣預測、股票、健康諮詢）
- 簡短、口語、繁體中文
- 每則回覆控制在 100 字以內
"""


# 結束關鍵字 — 嚴格比對（去頭尾空白後完全相等）
END_KEYWORDS = {
    "bye",
    "Bye",
    "BYE",
    "/end",
    "/bye",
    "再見",
    "掰掰",
    "結束",
    "結束對話",
    "下次見",
    "end",
    "End",
}


# 結束時的告別訊息（reply API 用 — 使用者主動結束）
GOODBYE_USER_INITIATED = "好的，這次對話結束 ✅\n再傳訊息給我就會開始新對話、記憶會重置。"

# 結束時的告別訊息（push API 用 — 自動超時）
GOODBYE_TIMEOUT = "🌙 30 分鐘沒互動，這次對話自動結束。\n再傳訊息給我就會開始新對話、記憶會重置。"


def is_end_keyword(text: str) -> bool:
    """是不是結束關鍵字（簡單 strip + 直接比對）。"""
    return text.strip() in END_KEYWORDS
